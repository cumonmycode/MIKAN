/** Строка о дне выхода, чтобы модель держала в голове контекст времени. */
export function whenLine(ctx: AppContext, publishAt: string | null): string {
  const ms = publishAt ? Date.parse(publishAt) : Number.NaN;
  if (!Number.isFinite(ms)) return 'Дата выхода не назначена.';
  const at = DateTime.fromMillis(ms, { zone: studioTimezone(ctx.db) });
  return `Выходит ${at.toISODate()} (${WEEKDAYS[at.weekday]}) в ${at.toFormat('HH:mm')} по местному времени.`;
}
