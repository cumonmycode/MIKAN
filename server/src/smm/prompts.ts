/** Дни недели по номеру ISO (luxon: 1 — понедельник). */
const WEEKDAYS = ['', 'понедельник', 'вторник', 'среда', 'четверг', 'пятница', 'суббота', 'воскресенье'];

export function todayLine(ctx: AppContext): string {
  const tz = studioTimezone(ctx.db);
  const now = DateTime.now().setZone(tz);
  return `Сегодня ${now.toISODate()}, ${WEEKDAYS[now.weekday]} (время местное, ${tz}).`;
}

// ─── Направления ─────────────────────────────────────────────────────────────

const TRANSLIT: Record<string, string> = {
  а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', ё: 'e', ж: 'zh', з: 'z', и: 'i', й: 'y', к: 'k', л: 'l', м: 'm',
  н: 'n', о: 'o', п: 'p', р: 'r', с: 's', т: 't', у: 'u', ф: 'f', х: 'h', ц: 'ts', ч: 'ch', ш: 'sh', щ: 'sch',
  ъ: '', ы: 'y', ь: '', э: 'e', ю: 'yu', я: 'ya',
};
const SLUG_MAX = 24;
const DIRECTIONS_MAX = 20;

/** Короткий латинский ключ по началу строки (до «:», «—», запятой): «Уход и заживление: …» → «uhod-i-zazhivlenie». */
function slugOf(title: string): string {
  const head = title.split(/[:—–(,.;]| - /)[0] ?? title;
  const latin = [...head.toLowerCase()].map((ch) => TRANSLIT[ch] ?? ch).join('');
  const words = latin.replace(/[^a-z0-9]+/g, ' ').trim().split(' ').filter(Boolean);
  let slug = '';
  for (const word of words) {
    const next = slug ? `${slug}-${word}` : word;
    if (next.length > SLUG_MAX) break;
    slug = next;
  }
  return slug || (words[0] ?? '').slice(0, SLUG_MAX);
}

/**
 * Направления профиля — каждое должно звучать в плане. Из `settings.directions`, по строке (маркеры списка
 * отбрасываются); ключ — короткий латинский slug начала строки, стабилен, пока не меняется её начало.
 */
export function directionsOf(settings: Pick<SmmSettings, 'directions'>): { key: string; title: string }[] {
  const out: { key: string; title: string }[] = [];
  const seen = new Set<string>();
  for (const raw of settings.directions.split('\n')) {
    const title = raw.replace(/^\s*(?:[-–—•*·]|\d+[.)])\s*/, '').trim();
    if (!title) continue;
    const base = slugOf(title) || `d${out.length + 1}`;
    let key = base;
    for (let n = 2; seen.has(key); n += 1) key = `${base}-${n}`;
    seen.add(key);
    out.push({ key, title });
    if (out.length >= DIRECTIONS_MAX) break;
  }
  return out;
}

